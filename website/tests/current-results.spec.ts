import { expect, test } from "@playwright/test";

test("current study tabs retain all trainings and task-dependent findings", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/#results");
  const panel = page.getByRole("tabpanel", { name: /High-level policies/ });
  await expect(panel.locator("svg[role=img]").filter({visible:true})).toHaveCount(1);
  await page.addStyleTag({content:".landing-header { position:static!important; } .skip-link { display:none!important; }"});
  await panel.screenshot({ path: testInfo.outputPath("policies.png") });
  await panel.locator(".study-breakdown > summary").click();
  await expect(panel.getByRole("img", { name: /^CollectShell/ })).toHaveAttribute("aria-label", /DP: 7, 9, 14 successes out of 30/);
  await page.getByRole("tab", { name: /Policy × control/ }).click();
  await expect(page.locator("#study-panel")).toContainText("4.0% → 29.2%");
  await expect(page.getByRole("img", { name: /^OpenHatch. Full I:/ })).toHaveAttribute("aria-label", /No I: 0, 0, 0/);
  await page.locator("#study-panel").screenshot({ path: testInfo.outputPath("controller.png") });
  await page.getByRole("button", { name: "Action interfaces", exact: true }).click();
  await expect(page.locator("#study-panel")).toContainText("-34.4 pp");
  await expect(page.locator("#study-panel")).toContainText("+3.3 pp");
  await expect(page.locator("#study-panel")).toContainText("not evidence of equivalence");
  await page.locator("#study-panel").screenshot({ path: testInfo.outputPath("interfaces.png") });
  await page.getByRole("button", { name: "Water current", exact: true }).click();
  await expect(page.locator("#study-panel")).toContainText("540 episodes");
  await expect(page.locator("#study-panel")).toContainText("87.8% to 64.4%");
  await expect(page.locator("#results video")).toHaveCount(0);
  await page.getByRole("button", {name:"Motor-force RMS (N)",exact:true}).click();
  await expect(page.getByRole("img", {name:/Open hatch: Motor-force RMS/})).toBeVisible();
  await page.locator("#study-panel").screenshot({path:testInfo.outputPath("current.png")});
  await page.getByRole("tab", { name: /Policy × control/ }).press("ArrowRight");
  await expect(page.getByRole("tab", { name: /Embodiments/ })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Two-arm manipulation", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Two-arm manipulation", exact: true }).click();
  await expect(page.getByRole("img", {name:/Valve rotation/})).toBeVisible();
  await expect(page.locator("#results video")).toHaveCount(0);
  await page.locator("#study-panel").screenshot({path:testInfo.outputPath("embodiments.png")});
  await page.getByRole("tab", {name:/VLA \/ SmolVLA/}).click();
  await expect(page.locator("#vla-heading")).toContainText("Vision–language–action policies");
  await expect(page.locator("#study-panel")).toContainText("270 test episodes");
  await expect(page.locator(".vla-results .study-chart")).toHaveCount(3);
  await expect(page.locator("#study-panel")).toContainText("SmolVLA");
  await expect(page.locator("#results video")).toHaveCount(0);
  await page.locator("#study-panel").screenshot({path:testInfo.outputPath("vla.png")});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const pdf = await page.request.get("/static/paper/WasserMan-RAL-8pages.pdf");
  expect((await pdf.body()).subarray(0, 5).toString()).not.toBe("%PDF-");
  await expect(page.locator('a[href$=".pdf"]')).toHaveCount(0);
  expect(errors).toEqual([]);
});
